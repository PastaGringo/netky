import { useRouter } from '@tanstack/react-router'
import { useEffect, useState } from 'react'

type State =
  | { step: 'idle' }
  | { step: 'starting' }
  | { step: 'scan'; id: string; url: string; qr: string }
  | { step: 'done' }
  | { step: 'error'; message: string }

/** "I run this server": confirm a claim by signing in with Pubky Ring. */
export function ConfirmOperator({ homeserver }: { homeserver: string }) {
  const router = useRouter()
  const [state, setState] = useState<State>({ step: 'idle' })

  useEffect(() => {
    if (state.step !== 'scan') return
    let stop = false
    const tick = async () => {
      if (stop) return
      const res = await fetch(`/api/confirm/${state.id}`).catch(() => null)
      const s = (await res?.json().catch(() => null)) as {
        status: string
        message: string | null
      } | null
      if (stop) return
      if (s?.status === 'done') {
        setState({ step: 'done' })
        await router.invalidate()
        return
      }
      if (s?.status === 'error' || res?.status === 404) {
        setState({
          step: 'error',
          message: s?.message ?? 'Something went wrong.',
        })
        return
      }
      setTimeout(tick, 2000)
    }
    const t = setTimeout(tick, 2000)
    return () => {
      stop = true
      clearTimeout(t)
    }
  }, [state, router])

  async function start() {
    setState({ step: 'starting' })
    const res = await fetch('/api/confirm', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ homeserver }),
    }).catch(() => null)
    const body = (await res?.json().catch(() => null)) as {
      id?: string
      url?: string
      qr?: string
      error?: string
    } | null
    if (!res?.ok || !body?.id || !body.url || !body.qr) {
      setState({
        step: 'error',
        message: body?.error ?? 'Could not reach Netky.',
      })
      return
    }
    setState({ step: 'scan', id: body.id, url: body.url, qr: body.qr })
  }

  if (state.step === 'done')
    return (
      <p className="m-0 mt-3 text-sm text-cyan">Confirmed. Thanks, operator.</p>
    )

  return (
    <div className="mt-3 border border-cyan/50 bg-panel/90 p-4 text-sm">
      {state.step === 'scan' ? (
        <div className="flex flex-col gap-4 sm:flex-row sm:items-center">
          <div
            className="relative z-[70] w-48 max-w-full shrink-0 bg-white p-1 [&>svg]:block [&>svg]:h-auto [&>svg]:w-full"
            role="img"
            aria-label="QR code to scan with Pubky Ring"
            // SVG generated by the qrcode library on the server, from the auth URL only.
            dangerouslySetInnerHTML={{ __html: state.qr }}
          />
          <div className="min-w-0">
            <p className="m-0">Scan with Pubky Ring, using the operator key.</p>
            <p className="m-0 mt-1 text-dim">
              Netky only asks to write in <code>/pub/netky/</code>, adds this
              server to <code>operates.txt</code>, then signs out.
            </p>
            <a
              href={state.url}
              className="mt-3 inline-flex min-h-[44px] items-center border border-cyan px-4 text-cyan hover:bg-cyan hover:text-void"
            >
              open Pubky Ring on this device
            </a>
            <p className="m-0 mt-2 text-xs text-dim">Waiting for approval…</p>
          </div>
        </div>
      ) : (
        <>
          <p className="m-0">
            Are you the operator named above? Confirm with Pubky Ring and your
            name and avatar will show on this server.
          </p>
          {state.step === 'error' ? (
            <p className="m-0 mt-2 text-red">{state.message}</p>
          ) : null}
          <button
            type="button"
            onClick={start}
            disabled={state.step === 'starting'}
            className="mt-3 inline-flex min-h-[44px] items-center border border-cyan px-4 text-cyan hover:bg-cyan hover:text-void disabled:opacity-50"
          >
            {state.step === 'starting' ? 'starting…' : 'I run this server'}
          </button>
        </>
      )}
    </div>
  )
}
