import { createFileRoute } from '@tanstack/react-router'
import { useCallback, useEffect, useState } from 'react'

import { Avatar, fmtDate } from '#/components/ui'
import type { AppAccount } from '#/server/admin'

export const Route = createFileRoute('/admin')({
  head: () => ({
    meta: [
      { title: 'Admin · netky' },
      { name: 'robots', content: 'noindex, nofollow' },
    ],
  }),
  component: Admin,
})

interface Me {
  admin: string | null
  account?: AppAccount | null
}

interface Check {
  ok: boolean
  capabilities: Array<string>
  message: string | null
}

const button =
  'inline-flex min-h-[44px] items-center border border-cyan px-4 text-cyan hover:bg-cyan hover:text-void disabled:opacity-50'

async function api(path: string, method = 'GET', json?: unknown) {
  const res = await fetch(path, {
    method,
    ...(json === undefined
      ? {}
      : {
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify(json),
        }),
  }).catch(() => null)
  const body = (await res?.json().catch(() => null)) as Record<
    string,
    unknown
  > | null
  if (!res?.ok)
    throw new Error(
      typeof body?.error === 'string' ? body.error : 'Could not reach Netky.',
    )
  return body ?? {}
}

/** Shows a Pubky Ring QR code and waits for the approval. */
function RingFlow({
  path,
  hint,
  onDone,
}: {
  path: string
  hint: string
  onDone: () => void
}) {
  const [flow, setFlow] = useState<{ url: string; qr: string } | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)

  useEffect(() => {
    if (!flow) return
    let stop = false
    let timer: ReturnType<typeof setTimeout>
    const tick = async () => {
      const res = await fetch('/api/admin/flow').catch(() => null)
      const s = (await res?.json().catch(() => null)) as {
        status?: string
        message?: string | null
      } | null
      if (stop) return
      if (s?.status === 'done') return onDone()
      if (s?.status === 'pending' || !res) {
        timer = setTimeout(tick, 2000)
        return
      }
      setFlow(null)
      setError(s?.message ?? 'Something went wrong.')
    }
    timer = setTimeout(tick, 2000)
    return () => {
      stop = true
      clearTimeout(timer)
    }
  }, [flow, onDone])

  async function start() {
    setBusy(true)
    setError(null)
    try {
      setFlow((await api(path, 'POST')) as { url: string; qr: string })
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    }
    setBusy(false)
  }

  if (!flow)
    return (
      <>
        {error ? <p className="m-0 mb-3 text-sm text-red">{error}</p> : null}
        <button
          type="button"
          onClick={start}
          disabled={busy}
          className={button}
        >
          {busy ? 'starting…' : 'continue with Pubky Ring'}
        </button>
      </>
    )
  return (
    <div className="flex flex-col gap-4 sm:flex-row sm:items-center">
      <div
        className="relative z-[70] w-48 max-w-full shrink-0 bg-white p-1 [&>svg]:block [&>svg]:h-auto [&>svg]:w-full"
        role="img"
        aria-label="QR code to scan with Pubky Ring"
        // SVG generated by the qrcode library on the server, from the auth URL only.
        dangerouslySetInnerHTML={{ __html: flow.qr }}
      />
      <div className="min-w-0 text-sm">
        <p className="m-0">{hint}</p>
        <a href={flow.url} className={`${button} mt-3`}>
          open Pubky Ring on this device
        </a>
        <p className="m-0 mt-2 text-xs text-dim">Waiting for approval…</p>
      </div>
    </div>
  )
}

function Admin() {
  const [me, setMe] = useState<Me | null>(null)
  const [error, setError] = useState<string | null>(null)

  const refresh = useCallback(() => {
    api('/api/admin/me')
      .then((m) => setMe(m as unknown as Me))
      .catch((e: unknown) =>
        setError(e instanceof Error ? e.message : String(e)),
      )
  }, [])
  useEffect(refresh, [refresh])

  return (
    <section className="mx-auto w-full max-w-3xl px-4 pt-12 pb-16 sm:px-6">
      <h1 className="m-0 font-display text-6xl leading-none">admin</h1>
      {error ? <p className="mt-4 text-red">{error}</p> : null}
      {!me && !error ? <p className="mt-4 text-dim">Loading…</p> : null}
      {me && !me.admin ? (
        <div className="mt-6 border bg-panel/90 p-4">
          <p className="m-0 mb-3 text-sm">
            Reserved for the operator of this site. Signing in grants Netky no
            access to your data: it only proves your key.
          </p>
          <RingFlow
            path="/api/admin/login"
            hint="Scan with Pubky Ring, using the admin key."
            onDone={refresh}
          />
        </div>
      ) : null}
      {me?.admin ? <Dashboard me={me} refresh={refresh} /> : null}
    </section>
  )
}

function Dashboard({ me, refresh }: { me: Me; refresh: () => void }) {
  const [check, setCheck] = useState<Check | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)
  const account = me.account ?? null

  const run = async (fn: () => Promise<void>) => {
    setBusy(true)
    setError(null)
    try {
      await fn()
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    }
    setBusy(false)
  }

  return (
    <>
      <p className="mt-3 text-sm break-all text-dim">
        signed in as pubky{me.admin} ·{' '}
        <button
          type="button"
          className="underline hover:text-red"
          onClick={() =>
            run(() => api('/api/admin/logout', 'POST').then(refresh))
          }
        >
          sign out
        </button>
      </p>

      <h2 className="m-0 mt-8 font-display text-3xl">
        <span className="text-dim">$</span> application account
      </h2>
      <p className="mt-2 text-sm text-dim">
        The Pubky account Netky posts with on pubky.app. Use a dedicated account
        rather than your personal one: its access is limited to{' '}
        <code>/pub/pubky.app/posts/</code>.
      </p>
      {error ? <p className="mt-2 text-sm text-red">{error}</p> : null}
      <div className="mt-3 border bg-panel/90 p-4">
        {account ? (
          <>
            <div className="flex items-center gap-3">
              <Avatar src={account.avatar} name={account.name} size={40} />
              <div className="min-w-0">
                <div>{account.name ?? 'no name on Nexus yet'}</div>
                <div className="text-xs break-all text-dim">
                  pubky{account.pubkey}
                </div>
                <div className="text-xs text-dim">
                  connected {fmtDate(account.linkedAt)}
                </div>
              </div>
            </div>
            {check ? (
              <p
                className={`m-0 mt-3 text-sm ${check.ok ? 'text-green' : 'text-red'}`}
              >
                {check.ok
                  ? `Session works · access: ${check.capabilities.join(', ')}`
                  : check.message}
              </p>
            ) : null}
            <div className="mt-4 flex flex-wrap gap-2">
              <button
                type="button"
                disabled={busy}
                className={button}
                onClick={() =>
                  run(async () => {
                    setCheck(
                      (await api('/api/admin/account')) as unknown as Check,
                    )
                    refresh()
                  })
                }
              >
                check session
              </button>
              <button
                type="button"
                disabled={busy}
                className="inline-flex min-h-[44px] items-center border border-red px-4 text-red hover:bg-red hover:text-void disabled:opacity-50"
                onClick={() =>
                  run(async () => {
                    await api('/api/admin/account', 'DELETE')
                    setCheck(null)
                    refresh()
                  })
                }
              >
                disconnect
              </button>
            </div>
          </>
        ) : (
          <>
            <p className="m-0 mb-3 text-sm">No account connected.</p>
            <RingFlow
              path="/api/admin/account"
              hint="Scan with Pubky Ring, using the account Netky will post with."
              onDone={refresh}
            />
          </>
        )}
      </div>
      {account ? <Publishing /> : null}
    </>
  )
}

interface Last {
  at: number | null
  uri: string | null
  error: string | null
}

interface PublishingStatus {
  daily: {
    enabled: boolean
    hourUtc: number
    publishedToday: boolean
    preview: string
    last: Last
  }
  announcements: { enabled: boolean; pending: Array<string>; last: Last }
}

function LastResult({ last }: { last: Last }) {
  if (last.error)
    return (
      <p className="m-0 mt-2 text-xs text-red">Last try failed: {last.error}</p>
    )
  if (!last.uri) return null
  return (
    <p className="m-0 mt-2 text-xs break-all text-dim">
      Last post {fmtDate(last.at)}: {last.uri}
    </p>
  )
}

function Publishing() {
  const [status, setStatus] = useState<PublishingStatus | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)

  useEffect(() => {
    api('/api/admin/publishing')
      .then((s) => setStatus(s as unknown as PublishingStatus))
      .catch((e: unknown) =>
        setError(e instanceof Error ? e.message : String(e)),
      )
  }, [])

  const send = async (json: unknown) => {
    setBusy(true)
    setError(null)
    try {
      setStatus(
        (await api(
          '/api/admin/publishing',
          'POST',
          json,
        )) as unknown as PublishingStatus,
      )
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    }
    setBusy(false)
  }

  return (
    <>
      <h2 className="m-0 mt-8 font-display text-3xl">
        <span className="text-dim">$</span> publishing
      </h2>
      {error ? <p className="mt-2 text-sm text-red">{error}</p> : null}
      {!status ? (
        <p className="mt-2 text-sm text-dim">Loading…</p>
      ) : (
        <div className="mt-3 space-y-3">
          <div className="border bg-panel/90 p-4">
            <label className="flex min-h-[44px] items-center gap-3">
              <input
                type="checkbox"
                className="size-5"
                checked={status.daily.enabled}
                disabled={busy}
                onChange={(e) => send({ daily: e.target.checked })}
              />
              <span>Daily report, around {status.daily.hourUtc}:37 UTC</span>
            </label>
            <pre className="mt-2 overflow-x-auto border p-3 text-xs whitespace-pre-wrap">
              {status.daily.preview}
            </pre>
            <button
              type="button"
              disabled={busy || status.daily.publishedToday}
              className={`${button} mt-3`}
              onClick={() => {
                if (window.confirm('Publish this report on pubky.app now?'))
                  void send({ publishNow: true })
              }}
            >
              {status.daily.publishedToday
                ? 'published today'
                : 'publish it now'}
            </button>
            <LastResult last={status.daily.last} />
          </div>
          <div className="border bg-panel/90 p-4">
            <label className="flex min-h-[44px] items-center gap-3">
              <input
                type="checkbox"
                className="size-5"
                checked={status.announcements.enabled}
                disabled={busy}
                onChange={(e) => send({ announcements: e.target.checked })}
              />
              <span>Announce new homeservers</span>
            </label>
            <p className="m-0 mt-1 text-xs text-dim">
              After 24 h online with 90% uptime, plain domains only, 3 a day at
              most. Servers known when you turn this on are not announced.
            </p>
            {status.announcements.pending.length ? (
              <p className="m-0 mt-2 text-xs">
                Next: {status.announcements.pending.join(', ')}
              </p>
            ) : null}
            <LastResult last={status.announcements.last} />
          </div>
        </div>
      )}
    </>
  )
}
