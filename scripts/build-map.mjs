// Generates src/lib/world-map.ts: a dot-matrix world map (one SVG path) and
// the projected position of each country, keyed by ISO 3166-1 alpha-2 code.
// Run once with `node scripts/build-map.mjs`; the output is committed, so no
// map library ships to the browser.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoArea, geoContains, geoEqualEarth, geoPath } from 'd3-geo'
import countries from 'i18n-iso-countries'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const topo = JSON.parse(
  readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'),
)

const W = 960
const H = 440
const STEP = 7 // distance between dots, in map units

const all = feature(topo, topo.objects.countries).features
// No homeserver in Antarctica, and it eats a third of the height.
const shapes = all.filter((f) => f.properties.name !== 'Antarctica')
const land = feature(topo, topo.objects.land)

const projection = geoEqualEarth().fitExtent(
  [
    [4, 4],
    [W - 4, H - 4],
  ],
  { type: 'FeatureCollection', features: shapes },
)
const path = geoPath(projection)

// Dot grid: keep the points whose inverse projection falls on land.
let dots = ''
let count = 0
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const ll = projection.invert([x, y])
    if (!ll || ll[1] < -60) continue
    if (geoContains(land, ll)) {
      dots += `M${x} ${y}h0`
      count++
    }
  }
}

// Finer grid for the Europe zoom, where most homeservers are.
const EUROPE = { x: 445, y: 38, w: 105, h: 64 }
const FINE = 1.9
let euDots = ''
let euCount = 0
for (let y = EUROPE.y + FINE / 2; y < EUROPE.y + EUROPE.h; y += FINE) {
  for (let x = EUROPE.x + FINE / 2; x < EUROPE.x + EUROPE.w; x += FINE) {
    const ll = projection.invert([x, y])
    if (ll && geoContains(land, ll)) {
      euDots += `M${x.toFixed(1)} ${y.toFixed(1)}h0`
      euCount++
    }
  }
}

// Country anchor: centroid of its largest polygon, so that France sits in
// Europe and not halfway to French Guiana.
const centroids = {}
for (const f of all) {
  const a2 = countries.numericToAlpha2(f.id)
  if (!a2) continue
  let geom = f.geometry
  if (geom.type === 'MultiPolygon') {
    const biggest = geom.coordinates
      .map((coords) => ({ type: 'Polygon', coordinates: coords }))
      .sort((a, b) => geoArea(b) - geoArea(a))[0]
    geom = biggest
  }
  const [x, y] = path.centroid(geom)
  if (Number.isFinite(x) && Number.isFinite(y))
    centroids[a2] = [Math.round(x), Math.round(y)]
}
// Too small to be in the 110m file, but plausible homeserver locations.
for (const [a2, lon, lat] of [
  ['SG', 103.8, 1.35],
  ['HK', 114.17, 22.3],
  ['LU', 6.13, 49.61],
  ['MT', 14.4, 35.9],
  ['BH', 50.55, 26.07],
  ['MC', 7.42, 43.74],
  ['LI', 9.55, 47.16],
  ['AD', 1.52, 42.5],
]) {
  if (!centroids[a2]) centroids[a2] = projection([lon, lat]).map(Math.round)
}

const out = `// Generated by scripts/build-map.mjs from world-atlas (Natural Earth, public
// domain). Do not edit by hand.
export const MAP_WIDTH = ${W}
export const MAP_HEIGHT = ${H}
/** ${count} land dots, drawn as zero-length segments with round caps. */
export const MAP_DOTS = '${dots}'
/** Europe zoom box, in map units. */
export const MAP_EUROPE = ${JSON.stringify(EUROPE)}
/** ${euCount} finer land dots inside the Europe box. */
export const MAP_DOTS_EUROPE = '${euDots}'
/** Projected anchor of each country, by ISO 3166-1 alpha-2 code. */
export const MAP_ANCHORS: Record<string, readonly [number, number]> = ${JSON.stringify(centroids)}
`
writeFileSync(new URL('../src/lib/world-map.ts', import.meta.url), out)
console.log(
  `${count} dots, ${Object.keys(centroids).length} countries, ${(out.length / 1024).toFixed(1)} KB`,
)
